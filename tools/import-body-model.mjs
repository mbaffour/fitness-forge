// Generates src/data/body-model.js from react-muscle-highlighter (MIT).
// Usage: node tools/import-body-model.mjs <path-to-package>
// Extracts the anatomical muscle paths (bezier, front+back) and the body
// outline, remapping the project's muscle vocabulary onto our 12 group ids.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const __dir = dirname(fileURLToPath(import.meta.url));
const pkg = process.argv[2];
if (!pkg) { console.error('usage: node tools/import-body-model.mjs <package dir>'); process.exit(1); }

const { bodyFront } = await import(resolve(pkg, 'dist/esm/assets/bodyFront.js'));
const { bodyBack }  = await import(resolve(pkg, 'dist/esm/assets/bodyBack.js'));

// their slug -> our muscle-group id (null = neutral anatomy, drawn but not tappable)
const MAP = {
  chest: 'chest', obliques: 'core', abs: 'core', biceps: 'biceps', triceps: 'triceps',
  trapezius: 'traps', deltoids: 'shoulders', quadriceps: 'quads', adductors: 'quads',
  calves: 'calves', tibialis: 'calves', forearm: 'forearms',
  'upper-back': 'back', 'lower-back': 'back', gluteal: 'glutes', hamstring: 'hamstrings',
  neck: null, knees: null, hands: null, ankles: null, feet: null, head: null, hair: null,
};

function convert(list, view) {
  const out = [];
  for (const m of list) {
    if (!(m.slug in MAP)) { console.warn(`  ! unmapped slug: ${m.slug} (${view})`); continue; }
    const paths = [...(m.path?.left || []), ...(m.path?.right || [])];
    if (!paths.length) continue;
    out.push({ group: MAP[m.slug], slug: m.slug, paths });
  }
  return out;
}

// The body outline lives in the SVG wrapper as two stroked border paths.
const wrapper = readFileSync(resolve(pkg, 'dist/esm/components/SvgMaleWrapper.js'), 'utf8');
const outlines = [...wrapper.matchAll(/d:\s*"((?:[^"\\]|\\.)*)"/g)].map(m => m[1]);
if (outlines.length < 2) console.warn('  ! expected 2 outline paths, got', outlines.length);

const front = convert(bodyFront, 'front');
const back  = convert(bodyBack,  'back');

const body = `// ═══════════════════════════════════════════
//   FITNESS FORGE — Anatomical body model
//   GENERATED by tools/import-body-model.mjs — do not edit by hand.
//   Source: react-muscle-highlighter (MIT, © 2024 My Muscle Contributors)
//   https://github.com/soroojshehryar/react-muscle-highlighter
//
//   Detailed bezier muscle paths, front + back, remapped from that project's
//   muscle vocabulary onto our 12 muscle-group ids. \`group: null\` = neutral
//   anatomy (head, neck, hands, feet) — drawn, but never tappable.
//   Front and back share one 1448×1448 space; each figure has its own viewBox.
// ═══════════════════════════════════════════

export const BODY_VIEWBOX_FRONT = '0 0 724 1448';
export const BODY_VIEWBOX_BACK  = '724 0 724 1448';
export const BODY_MODEL_ATTRIBUTION = 'Body model: react-muscle-highlighter · MIT';
export const BODY_MODEL_URL = 'https://github.com/soroojshehryar/react-muscle-highlighter';

// Body outline, drawn under the muscles so the figure reads as one silhouette.
export const BODY_OUTLINE_FRONT = ${JSON.stringify(outlines[0] || '')};
export const BODY_OUTLINE_BACK  = ${JSON.stringify(outlines[1] || '')};

export const BODY_FRONT = ${JSON.stringify(front)};

export const BODY_BACK = ${JSON.stringify(back)};
`;
writeFileSync(resolve(__dir, '../src/data/body-model.js'), body);

const groups = (l) => [...new Set(l.map(r => r.group).filter(Boolean))].sort();
console.log(`front: ${front.length} regions, ${front.reduce((n,r)=>n+r.paths.length,0)} paths`);
console.log(`back:  ${back.length} regions, ${back.reduce((n,r)=>n+r.paths.length,0)} paths`);
console.log('front groups:', groups(front).join(', '));
console.log('back groups: ', groups(back).join(', '));
console.log('outlines:', outlines.length, '| wrote src/data/body-model.js');

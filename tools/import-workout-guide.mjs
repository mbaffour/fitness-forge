// ═══════════════════════════════════════════
//   Fitness Forge — workout-guide importer
//   One-time generator (NOT shipped to the app).
//   Maps our exercises to workout-guide's OPENLY-LICENSED
//   animated illustrations (github.com/bryllim/workout-guide,
//   assets CC BY-SA 4.0, derived from Everkinetic).
//   Emits src/data/exercise-anim.js (URLs only — no media vendored).
//
//   Usage: node tools/import-workout-guide.mjs [path-to-manifest.json]
//   Manifest: raw.githubusercontent.com/bryllim/workout-guide/main/packages/workout-guide/manifest.json
// ═══════════════════════════════════════════

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { EXERCISES } from '../src/data/exercises.js';

const __dir = dirname(fileURLToPath(import.meta.url));
const manifestPath = process.argv[2] || resolve(__dir, 'wg-manifest.json');
const outPath = resolve(__dir, '../src/data/exercise-anim.js');

const wg = JSON.parse(readFileSync(manifestPath, 'utf8'));
const norm = (s) => String(s || '').toLowerCase().replace(/[^a-z0-9]/g, '');

// Build lookups from our DB: normalized name → our key.
const byName = new Map();
for (const [id, ex] of Object.entries(EXERCISES)) {
  const n = norm(ex.name);
  if (n && !byName.has(n)) byName.set(n, id);
}
const ourNames = [...byName.keys()];

const anim = {};
let exact = 0, fuzzy = 0;
for (const e of wg) {
  const wgN = norm(e.name);
  if (!wgN || !Array.isArray(e.frames) || e.frames.length < 2) continue;
  let key = byName.get(wgN);            // exact normalized-name match
  if (key) { exact++; }
  else {
    // fuzzy: our name ends-with / starts-with the WG name (e.g. "barbellbenchpress" ⊇ "benchpress")
    const cand = ourNames.find(n => (n.endsWith(wgN) || n.startsWith(wgN)) && Math.abs(n.length - wgN.length) <= 10);
    if (cand) { key = byName.get(cand); fuzzy++; }
  }
  if (key && !anim[key]) anim[key] = { slug: e.slug, frames: e.frames.length };
}

const count = Object.keys(anim).length;
const header = `// ═══════════════════════════════════════════
//   FITNESS FORGE — Animated exercise illustrations (workout-guide)
//   GENERATED by tools/import-workout-guide.mjs — do not edit by hand.
//
//   URLS ONLY — no media vendored. Assets are © Bryl Lim & Everkinetic,
//   licensed CC BY-SA 4.0 (https://creativecommons.org/licenses/by-sa/4.0/),
//   from github.com/bryllim/workout-guide. The app hotlinks the frame SVGs at
//   runtime and shows the required attribution. ${count} of ${Object.keys(EXERCISES).length} exercises matched.
// ═══════════════════════════════════════════

export const WG_BASE = 'https://raw.githubusercontent.com/bryllim/workout-guide/main/packages/workout-guide/assets/';
export const WG_ATTRIBUTION = '© Bryl Lim / Everkinetic · CC BY-SA 4.0';
export const WG_ATTRIBUTION_URL = 'https://github.com/bryllim/workout-guide';

// ourExerciseKey → { slug, frames } ; frame URL = WG_BASE + slug + '/frame-N.svg'
export const EXERCISE_ANIM = ${JSON.stringify(anim, null, 0)};
`;

writeFileSync(outPath, header);
console.log(`workout-guide entries: ${wg.length}`);
console.log(`matched: ${count} (exact ${exact}, fuzzy ${fuzzy})`);
console.log(`wrote: ${outPath}`);

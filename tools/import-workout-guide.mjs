// ═══════════════════════════════════════════
//   Fitness Forge — workout-guide importer
//   One-time generator (NOT shipped to the app).
//   Maps our exercises to workout-guide's OPENLY-LICENSED
//   animated illustrations (github.com/bryllim/workout-guide,
//   assets CC BY-SA 4.0, derived from Everkinetic).
//   Emits src/data/exercise-anim.js (URLs only — no media vendored).
//
//   Usage: node tools/import-workout-guide.mjs [path-to-manifest.json]
//   Manifest: raw.githubusercontent.com/bryllim/workout-guide/main/packages/workout-guide/manifest.json
// ═══════════════════════════════════════════

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { EXERCISES } from '../src/data/exercises.js';

const __dir = dirname(fileURLToPath(import.meta.url));
const manifestPath = process.argv[2] || resolve(__dir, 'wg-manifest.json');
const outPath = resolve(__dir, '../src/data/exercise-anim.js');
const outExPath = resolve(__dir, '../src/data/exercises-wg.js');

const wg = JSON.parse(readFileSync(manifestPath, 'utf8'));
const norm = (s) => String(s || '').toLowerCase().replace(/[^a-z0-9]/g, '');

// ── WG vocabulary → Forge taxonomy ──────────────────────────────────────────
// WG primaryMuscle/secondaryMuscles → our 12 muscle-group ids.
const MUS = {
  Chest: 'chest', Shoulders: 'shoulders', 'Rear Delts': 'shoulders',
  'Upper Back': 'back', Back: 'back', Lats: 'back', 'Lower Back': 'back',
  Hamstrings: 'hamstrings', 'Posterior Chain': 'hamstrings',
  Quads: 'quads', Legs: 'quads', Adductors: 'quads',
  Glutes: 'glutes', Hips: 'glutes', Calves: 'calves',
  Biceps: 'biceps', Triceps: 'triceps', Forearms: 'forearms', Core: 'core',
};
// WG equipment → our item-level `requires` ids ([] = bodyweight/anywhere).
const EQ = {
  Barbell: ['barbell'], Dumbbell: ['dumbbells'], Machine: ['machine'],
  Cable: ['cable'], Kettlebell: ['kettlebell'], 'Pull-up Bar': ['pull_up_bar'],
  Bench: ['bench'], 'Resistance Band': ['resistance_bands'],
  Bodyweight: [], Plate: [], Wall: [], Chair: [], Doorway: [], Towel: [],
  Box: [], 'Stability Ball': [],
};
const HOME_ITEMS = new Set(['dumbbells', 'kettlebell', 'resistance_bands', 'pull_up_bar', 'bench']);
const ISO_MUS = new Set(['Biceps', 'Triceps', 'Calves', 'Forearms', 'Rear Delts']);
const ISO_RE = /curl|raise|extension|fly|kickback|pushdown|shrug/i;

// Build lookups from our DB: normalized name → our key.
const byName = new Map();
for (const [id, ex] of Object.entries(EXERCISES)) {
  const n = norm(ex.name);
  if (n && !byName.has(n)) byName.set(n, id);
}
const ourNames = [...byName.keys()];

const anim = {};
const wgExercises = {};
let exact = 0, fuzzy = 0, added = 0, skipped = 0;
for (const e of wg) {
  const wgN = norm(e.name);
  if (!wgN || !Array.isArray(e.frames) || e.frames.length < 2) continue;
  let key = byName.get(wgN);            // exact normalized-name match
  if (key) { exact++; }
  else {
    // fuzzy: our name ends-with / starts-with the WG name (e.g. "barbellbenchpress" ⊇ "benchpress")
    const cand = ourNames.find(n => (n.endsWith(wgN) || n.startsWith(wgN)) && Math.abs(n.length - wgN.length) <= 10);
    if (cand) { key = byName.get(cand); fuzzy++; }
  }

  // Unmatched: add as a net-new Forge exercise if it's a trainable strength
  // movement (skip stretches + cardio — those belong outside the strength lib).
  if (!key) {
    if (e.isStretch === true || e.equipment === 'Cardio') { skipped++; continue; }
    const g = MUS[e.primaryMuscle];
    if (!g) { skipped++; continue; }
    const newKey = 'wg_' + e.slug.replace(/[^a-z0-9]+/gi, '_');
    if (newKey in EXERCISES || newKey in wgExercises) { skipped++; continue; }
    const groups = [g];
    for (const sm of (e.secondaryMuscles || [])) {
      const sg = MUS[sm];
      if (sg && !groups.includes(sg)) groups.push(sg);
    }
    const requires = EQ[e.equipment] ?? [];
    const equip = requires.length === 0
      ? ['bodyweight', 'home_basic', 'full_gym']
      : requires.every(i => HOME_ITEMS.has(i))
        ? ['home_basic', 'full_gym']
        : ['full_gym'];
    const type = (ISO_MUS.has(e.primaryMuscle) || ISO_RE.test(e.name)) ? 'isolation' : 'compound';
    wgExercises[newKey] = {
      name: e.name,
      muscle: e.primaryMuscle,
      groups,
      equip,
      requires,
      diff: 'int',
      type,
      musclesFull: { primary: [e.primaryMuscle], secondary: e.secondaryMuscles || [], stabilizers: [] },
      cues: [],
      commonErrors: [],
      youtubeId: '',
      exrxSlug: '',
      source: 'workout-guide',
    };
    key = newKey;
    added++;
  }

  if (key && !anim[key]) anim[key] = { slug: e.slug, frames: e.frames.length };
}

const count = Object.keys(anim).length;
const header = `// ═══════════════════════════════════════════
//   FITNESS FORGE — Animated exercise illustrations (workout-guide)
//   GENERATED by tools/import-workout-guide.mjs — do not edit by hand.
//
//   URLS ONLY — no media vendored. Assets are © Bryl Lim & Everkinetic,
//   licensed CC BY-SA 4.0 (https://creativecommons.org/licenses/by-sa/4.0/),
//   from github.com/bryllim/workout-guide. The app hotlinks the frame SVGs at
//   runtime and shows the required attribution. ${count} of ${Object.keys(EXERCISES).length} exercises matched.
// ═══════════════════════════════════════════

export const WG_BASE = 'https://raw.githubusercontent.com/bryllim/workout-guide/main/packages/workout-guide/assets/';
export const WG_ATTRIBUTION = '© Bryl Lim / Everkinetic · CC BY-SA 4.0';
export const WG_ATTRIBUTION_URL = 'https://github.com/bryllim/workout-guide';

// ourExerciseKey → { slug, frames } ; frame URL = WG_BASE + slug + '/frame-N.svg'
export const EXERCISE_ANIM = ${JSON.stringify(anim, null, 0)};
`;

writeFileSync(outPath, header);

const exHeader = `// ═══════════════════════════════════════════
//   FITNESS FORGE — Exercises derived from workout-guide
//   GENERATED by tools/import-workout-guide.mjs — do not edit by hand.
//
//   ${added} net-new strength exercises whose names did NOT match our library,
//   mapped from workout-guide's structured metadata (equipment, primary /
//   secondary muscles, exercise type). Each has a matching animation in
//   exercise-anim.js. Metadata © Bryl Lim / Everkinetic, CC BY-SA 4.0
//   (https://creativecommons.org/licenses/by-sa/4.0/), github.com/bryllim/workout-guide.
//   Merged into EXERCISES in exercises.js (curated + library entries win on clash).
// ═══════════════════════════════════════════

export const WG_EXERCISES = ${JSON.stringify(wgExercises, null, 0)};
`;
writeFileSync(outExPath, exHeader);

console.log(`workout-guide entries: ${wg.length}`);
console.log(`matched: ${count} (exact ${exact}, fuzzy ${fuzzy})`);
console.log(`net-new exercises: ${added} (skipped ${skipped} stretch/cardio/unmapped)`);
console.log(`wrote: ${outPath}`);
console.log(`wrote: ${outExPath}`);

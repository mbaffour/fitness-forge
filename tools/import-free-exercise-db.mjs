// ═══════════════════════════════════════════
//   Fitness Forge — free-exercise-db importer
//   One-time generator (NOT shipped to the app).
//   Transforms the public-domain free-exercise-db
//   (github.com/yuhonas/free-exercise-db, Unlicense)
//   into our exercise shape, dedups against the
//   hand-curated set, and writes
//   src/data/exercises-library.js.
//
//   Usage:  node tools/import-free-exercise-db.mjs [path-to-exercises.json]
//   Source JSON: raw.githubusercontent.com/yuhonas/free-exercise-db/main/dist/exercises.json
// ═══════════════════════════════════════════

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { EXERCISES } from '../src/data/exercises.js';

const __dir = dirname(fileURLToPath(import.meta.url));
const srcPath = process.argv[2] || resolve(__dir, 'fedb.json');
const outPath = resolve(__dir, '../src/data/exercises-library.js');

const fedb = JSON.parse(readFileSync(srcPath, 'utf8'));

// free-exercise-db muscle → our 12 groups
const MUSCLE_TO_GROUP = {
  abdominals: 'core', abductors: 'glutes', adductors: 'quads', biceps: 'biceps',
  calves: 'calves', chest: 'chest', forearms: 'forearms', glutes: 'glutes',
  hamstrings: 'hamstrings', lats: 'back', 'lower back': 'back', 'middle back': 'back',
  neck: 'traps', quadriceps: 'quads', shoulders: 'shoulders', traps: 'traps', triceps: 'triceps',
};

// free-exercise-db equipment → our required items ([] = bodyweight-anywhere)
const EQUIP_TO_REQUIRES = {
  barbell: ['barbell'], dumbbell: ['dumbbells'], kettlebells: ['kettlebell'],
  bands: ['resistance_bands'], cable: ['cable'], machine: ['machine'],
  'e-z curl bar': ['barbell'], 'body only': [], none: [], null: [],
  'foam roll': [], 'exercise ball': [], 'medicine ball': [], other: [],
};

const ALL_ITEMS = ['dumbbells','barbell','bench','kettlebell','resistance_bands','cable','pull_up_bar','machine','rings_trx','ab_wheel'];
const PRESET_ITEMS = {
  bodyweight: [],
  dumbbells:  ['dumbbells','bench'],
  home_basic: ['dumbbells','resistance_bands','pull_up_bar','bench'],
  full_gym:   ALL_ITEMS,
};
const DIFF = { beginner: 'beg', intermediate: 'int', expert: 'adv' };

const norm = (s) => String(s || '').toLowerCase().replace(/[^a-z0-9]/g, '');
const title = (s) => String(s || '').replace(/\b\w/g, c => c.toUpperCase());
const uniq = (a) => [...new Set(a)];

// Existing coverage to dedup against (hand-curated entries win).
const existingImgKeys = new Set(Object.values(EXERCISES).map(e => (e.imgKey || '').toLowerCase()).filter(Boolean));
const existingNames    = new Set(Object.values(EXERCISES).map(e => norm(e.name)));

const out = {};
let skippedDup = 0, skippedNoImg = 0;

for (const e of fedb) {
  if (!e.images || !e.images.length) { skippedNoImg++; continue; }          // need a preview image
  if (existingImgKeys.has((e.id || '').toLowerCase()) || existingNames.has(norm(e.name))) { skippedDup++; continue; }

  const primary   = (e.primaryMuscles   || []);
  const secondary = (e.secondaryMuscles || []);
  const groups = uniq([...primary, ...secondary].map(m => MUSCLE_TO_GROUP[m]).filter(Boolean));
  if (!groups.length) continue;                                              // can't place it → skip

  const requires = uniq(EQUIP_TO_REQUIRES[String(e.equipment)] ?? []);
  const owned = new Set(requires);
  const equip = Object.keys(PRESET_ITEMS).filter(p => requires.every(i => PRESET_ITEMS[p].includes(i)));

  const key = 'fx_' + String(e.id).replace(/[^A-Za-z0-9]/g, '_');
  out[key] = {
    name: e.name,
    muscle: uniq(primary.map(title)).join(' / ') || title(groups[0]),
    groups,
    equip,
    requires,
    diff: DIFF[e.level] || 'int',
    type: e.mechanic === 'isolation' ? 'isolation' : 'compound',
    imgKey: e.id,
    musclesFull: { primary: primary.map(title), secondary: secondary.map(title), stabilizers: [] },
    cues: e.instructions || [],
    commonErrors: [],
    youtubeId: '',
    exrxSlug: '',
    tag: e.category || 'strength',
    source: 'free-exercise-db',
  };
}

const count = Object.keys(out).length;
const header = `// ═══════════════════════════════════════════
//   FITNESS FORGE — Imported Exercise Library
//   GENERATED by tools/import-free-exercise-db.mjs — do not edit by hand.
//   Source: free-exercise-db (github.com/yuhonas/free-exercise-db)
//   Licence: Unlicense (public domain). Images served from the same repo.
//   ${count} exercises, merged into EXERCISES in exercises.js (curated entries win).
// ═══════════════════════════════════════════

export const LIBRARY_EXERCISES = ${JSON.stringify(out, null, 0)};
`;

writeFileSync(outPath, header);
console.log(`fedb entries: ${fedb.length}`);
console.log(`skipped (dup): ${skippedDup}, skipped (no image): ${skippedNoImg}`);
console.log(`imported: ${count}`);
console.log(`wrote: ${outPath}`);
